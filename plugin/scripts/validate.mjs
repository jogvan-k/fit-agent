import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { z } from 'zod';
import { configSchema, inputs } from '../dist/schemas.js';
const json = async (path) => JSON.parse(await readFile(path, 'utf8'));
const pkg = await json('package.json'), manifest = await json('openclaw.plugin.json');
assert.equal(pkg.name, '@jogvan-k/fit-agent');
assert.equal(pkg.version, manifest.version);
assert.equal(manifest.id, 'fit-agent');
assert.deepEqual(manifest.categories, ['scheduling']);
assert.deepEqual(manifest.configSchema, z.toJSONSchema(configSchema, { io: 'input' }));
assert.deepEqual(manifest.contracts.tools, Object.keys(inputs).map((name) => `fit_agent_${name}`));
assert.equal(pkg.peerDependencies.openclaw, pkg.openclaw.build.openclawVersion);
for (const path of [...pkg.openclaw.extensions, 'LICENSE', 'README.md', 'assets/icon.png']) assert((await stat(path)).isFile());
const icon = await readFile('assets/icon.png');
assert(icon.length < 512 * 1024);
assert.equal(icon.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
for (const name of Object.keys(inputs)) for (const suffix of ['input', 'result']) await json(`schemas/${name}.${suffix}.json`);
console.log('Package identity, compatibility, manifest, six tool schema pairs, entrypoint, license and PNG validated.');
